const norm = (text: string) => text.trim().toLowerCase().replace(/_/g, " ");

/** Urdu for a known backend label; anything unrecognised is returned unchanged. */
export function translateTerm(text: string | null | undefined, lang: "en" | "ur"): string {
  if (!text) return "";
  if (lang !== "ur") return text;
  return termsUr[norm(text)] ?? text;
}
